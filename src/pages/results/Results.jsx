import { useLocation } from "react-router-dom";
import Header from "../../components/Header/Header";
import "./Results.css";

function Results() {
  // Принимаем данные из Home → navigate("/results", { state: { results } })
  const location = useLocation();
  const apiData = location.state?.results;

  // Если данных нет — fallback (моки)
  const sentimentData =
    apiData?.sentimentBreakdown ?? [
      { label: "True", value: 11, className: "pill-true" },
      { label: "Mostly True", value: 15, className: "pill-mostly-true" },
      { label: "Half True", value: 18, className: "pill-half-true" },
      { label: "Mostly False", value: 16, className: "pill-mostly-false" },
      { label: "False", value: 26, className: "pill-false" },
      { label: "Pants of Fire", value: 11, className: "pill-pants" },
    ];

  const summaryText =
    apiData?.summary ??
    `This post may be misleading.
The wording contains emotional triggers, lacks credible sources, 
and contradicts information from verified media outlets.`;

  const limePlaceholder =
    apiData?.lime ??
    "Radar chart placeholder — real LIME graph will be inserted here";

  return (
    <div className="results">
      <div className="results__overlay" />

      <div className="results__container">
        <Header />

        <main className="results__main page-enter">
          <div className="results__grid">
            {/* LEFT PANEL */}
            <section className="results__panel results__panel--intro">
              <h1 className="results__title">SOMAD Analysis Results</h1>
              <p className="results__subtitle">
                A comprehensive overview of social media data sentiment and key
                performance indicators.
              </p>
            </section>

            {/* SENTIMENT CHART */}
            <section className="results__card results__sentiment">
              <h2 className="results__section-title">
                Content Sentiment Breakdown
              </h2>

              <div className="results__sentiment-bars">
                {sentimentData.map((item, index) => (
                  <div key={item.label} className="sentiment-bar">
                    <div className="sentiment-bar__pill-wrapper">
                      <div
                        className={`sentiment-bar__pill ${item.className}`}
                        style={{ "--bar-delay": `${index * 0.08}s` }}
                      />
                    </div>
                    <span className="sentiment-bar__label">{item.label}</span>
                    <span className="sentiment-bar__value">
                      {item.value}%
                    </span>
                  </div>
                ))}
              </div>
            </section>

            {/* AI SUMMARY */}
            <section className="results__card results__summary">
              <h2 className="results__section-title">AI Summary</h2>

              <div className="results__summary-box">
                {summaryText.split("\n").map((line, idx) => (
                  <p key={idx}>{line}</p>
                ))}
              </div>

              <p className="results__summary-footer">generated by AI</p>
            </section>

            {/* LIME */}
            <section className="results__card results__lime">
              <h2 className="results__section-title">LIME keyword analysis</h2>

              <div className="results__lime-graph">
                <div className="results__lime-placeholder">
                  <span>{limePlaceholder}</span>
                  {!apiData && (
                    <p>
                      Higher value = stronger influence on the model's decision.
                    </p>
                  )}
                </div>
              </div>
            </section>
          </div>
        </main>

        <footer className="results__footer">
          <div className="results__footer-inner">
            <div className="results__footer-logo">SOMAD</div>
            <div className="results__footer-contact">
              <span>+7 0000000</span>
              <span>jshtwsldfj@gmail.com</span>
            </div>
          </div>
        </footer>
      </div>
    </div>
  );
}

export default Results;
